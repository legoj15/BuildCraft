"""Energy cross-mod pass on Fabric (issue #186): BuildCraft's FE converters against Team Reborn Energy mods.

Run: python scripts/smoke/generators/gen_crossmod_energy.py
     pwsh scripts/smoke/Invoke-InClientSmoke.ps1 -Nodes 26.3-fabric -Scenario scripts/smoke/scenarios/crossmod-energy.json
     pwsh scripts/smoke/Invoke-InClientSmoke.ps1 -Nodes 26.3-fabric -Scenario scripts/smoke/scenarios/crossmod-energy-notre.json

Which block takes and gives FE (read from TileEngineFE, TileDynamoMJ and BCEnergy.registerTransfer):
  FE engine (engine_rf)   takes FE on every side but its front (it also pulls FE from its neighbours), gives MJ out its front.
  MJ dynamo (mj_dynamo)   takes MJ on every side but its front, gives FE out its front (it also pushes FE into the block there).
  Both need a redstone signal. A creative engine (engine_creative) is the MJ source behind the dynamo.

Crossmod-energy, one lane per link, each lane on a fresh block (the rig is cleared first, so a stored amount that is not
zero came through the link):

  1  creative engine -> dynamo -> Energized Power battery box      the box's stored energy rose
  2  creative engine -> dynamo -> EP copper cable x2 -> battery box   BuildCraft into a cable network
  3  creative engine -> dynamo -> Tech Reborn LV storage unit         the unit's stored energy rose
  4  creative engine -> dynamo -> TR cable -> LV storage unit
  5  EP creative battery box -> FE engine -> Mining Well              the well dug (its tube is below it): BuildCraft ran on FE
  6  TR creative solar panel -> FE engine -> Mining Well              the same with the other mod's generator

Crossmod-energy-notre is the same BuildCraft blocks with NO Team Reborn Energy on the dev runtime (a 26.x Fabric
runClient has none unless `tre` is asked for): the blocks place and open their GUIs and nothing is logged.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from xmod import BC, Scenario, at  # noqa: E402

BASE = [0, 150, 0]
LANE = 4          # Z between lanes


def lane_z(n):
    return (n - 1) * LANE


def converter(S, n, sink_cmds):
    """Creative engine -> dynamo (both on a redstone block) pushing east into whatever `sink_cmds` places from x+2."""
    z = lane_z(n)
    S.cmd("lane %d: creative engine and dynamo, each on a redstone block" % n,
          "setblock %s minecraft:redstone_block" % at(0, -1, z),
          "setblock %s %sengine_creative[facing=east]" % (at(0, 0, z), BC),
          "setblock %s minecraft:redstone_block" % at(1, -1, z),
          "setblock %s %smj_dynamo[facing=east]" % (at(1, 0, z), BC), *sink_cmds)


def fe_engine(S, n, source, label):
    z = lane_z(n)
    S.cmd("lane %d: %s feeding an FE engine feeding a Mining Well" % (n, label),
          "setblock %s %s" % (at(0, 0, z), source),
          "setblock %s minecraft:redstone_block" % at(1, -1, z),
          "setblock %s %sengine_rf[facing=east]" % (at(1, 0, z), BC),
          "setblock %s %smining_well" % (at(2, 0, z), BC))


def energy_rig():
    S = Scenario("crossmod-energy", BASE,
                 description="Issue #186 on Fabric: BuildCraft's FE engine and MJ dynamo against Energized Power and Tech "
                             "Reborn through Team Reborn Energy, both directions. Generated by "
                             "generators/gen_crossmod_energy.py, whose docstring describes the lanes.",
                 mods=["tre", "energizedpower", "techreborn"], loaders=["fabric"], save="bc-xmod-energy", saveSeed="bc-smoke", freshSave=True)
    S.cmd("creative, daylight, the rig's chunks loaded", "gamemode creative @p", "difficulty peaceful", "time set day",
          "weather clear", "?forceload add {X-16} {Z-16} {X+32} {Z+32}")
    S.tp(8, 4, -4, 0, 25)
    S.wait(3000)
    S.cmd("a fresh rig: stone floor (Mining Wells dig down into it), air above",
          "fill {X-4} {Y-8} {Z-4} {X+12} {Y-1} {Z+28} minecraft:stone",
          "fill {X-4} {Y} {Z-4} {X+12} {Y+6} {Z+28} minecraft:air")

    converter(S, 1, ["setblock %s energizedpower:battery_box" % at(2, 0, lane_z(1))])
    converter(S, 2, ["setblock %s energizedpower:copper_cable" % at(2, 0, lane_z(2)),
                     "setblock %s energizedpower:copper_cable" % at(3, 0, lane_z(2)),
                     "setblock %s energizedpower:battery_box" % at(4, 0, lane_z(2))])
    converter(S, 3, ["setblock %s techreborn:low_voltage_su" % at(2, 0, lane_z(3))])
    converter(S, 4, ["setblock %s techreborn:copper_cable" % at(2, 0, lane_z(4)),
                     "setblock %s techreborn:low_voltage_su" % at(3, 0, lane_z(4))])
    fe_engine(S, 5, "energizedpower:creative_battery_box", "Energized Power's creative battery box")
    fe_engine(S, 6, "techreborn:creative_solar_panel", "Tech Reborn's creative solar panel")

    S.tp(17, 12, 10, 90, 30)
    S.wait(2500)
    S.shot("lanes-early", "six lanes in a row along Z, each starting with a creative engine and a dynamo (lanes 1 to 4) or "
                          "an Energized Power / Tech Reborn block beside an FE engine and a Mining Well (lanes 5, 6)")
    # Energy through the link: a block that starts at zero and reads above it.
    S.wait_cmd("lane 1: the EP battery box holds energy", "data get block %s" % at(2, 0, lane_z(1)),
               r"energy: [1-9]\d*L", 60)
    S.wait_cmd("lane 2: the battery box behind the EP cables holds energy", "data get block %s" % at(4, 0, lane_z(2)),
               r"energy: [1-9]\d*L", 60)
    S.wait_cmd("lane 3: the TR LV storage unit holds energy", "data get block %s PowerAcceptor.energy" % at(2, 0, lane_z(3)),
               r"[1-9]\d*L", 60)
    S.wait_cmd("lane 4: the TR LV storage unit behind the TR cable holds energy",
               "data get block %s PowerAcceptor.energy" % at(3, 0, lane_z(4)), r"[1-9]\d*L", 60)
    # FE into BuildCraft: the engine takes FE (its buffer fills) and the well digs, which needs the MJ the engine makes.
    for n, who in ((5, "EP creative battery box"), (6, "TR creative solar panel")):
        z = lane_z(n)
        S.wait_cmd("lane %d: the FE engine took FE from the %s" % (n, who), "data get block %s currentFe" % at(1, 0, z),
                   r"block data: [1-9]\d*$", 60)
        S.wait_cmd("lane %d: the Mining Well ran on it (a tube stands below the well)" % n,
                   "execute if block %s %stube" % (at(2, -1, z), BC), "passed", 90)
    S.wait(2000)
    S.tp(17, 12, 10, 90, 30)
    S.wait(1500)
    S.shot("lanes-late", "the same six lanes after the energy moved: lanes 5 and 6 have a pipe-like tube below their Mining "
                         "Well; the engines in lanes 5 and 6 are lit (FE engines burning)")
    S.echo("lane 1: EP battery box", "data get block %s" % at(2, 0, lane_z(1)))
    S.echo("lane 2: EP battery box behind the cables", "data get block %s" % at(4, 0, lane_z(2)))
    S.echo("lane 3: TR LV unit", "data get block %s PowerAcceptor.energy" % at(2, 0, lane_z(3)))
    S.echo("lane 4: TR LV unit behind the cable", "data get block %s PowerAcceptor.energy" % at(3, 0, lane_z(4)))
    S.echo("lane 5: FE engine", "data get block %s currentFe" % at(1, 0, lane_z(5)))
    S.echo("lane 6: FE engine", "data get block %s currentFe" % at(1, 0, lane_z(6)))
    return S


def notre_rig():
    S = Scenario("crossmod-energy-notre", BASE,
                 description="Issue #186 on Fabric: BuildCraft's FE blocks with no Team Reborn Energy loaded (a 26.x runClient "
                             "has none without the `tre` alias): the blocks place, open their GUIs and nothing is logged. "
                             "Generated by generators/gen_crossmod_energy.py.",
                 mods=[], loaders=["fabric"], save="bc-xmod-energy-notre", saveSeed="bc-smoke", freshSave=True)
    S.cmd("creative, daylight, the rig's chunks loaded", "gamemode creative @p", "difficulty peaceful", "time set day",
          "weather clear", "?forceload add {X-16} {Z-16} {X+32} {Z+32}")
    S.tp(4, 2, -4, 0, 20)
    S.wait(3000)
    S.cmd("a fresh rig", "fill {X-4} {Y-8} {Z-4} {X+12} {Y-1} {Z+12} minecraft:stone",
          "fill {X-4} {Y} {Z-4} {X+12} {Y+6} {Z+12} minecraft:air")
    S.cmd("creative engine, dynamo and FE engine on redstone blocks, a Mining Well after the FE engine",
          "setblock %s minecraft:redstone_block" % at(0, -1, 0),
          "setblock %s %sengine_creative[facing=east]" % (at(0, 0, 0), BC),
          "setblock %s minecraft:redstone_block" % at(1, -1, 0),
          "setblock %s %smj_dynamo[facing=east]" % (at(1, 0, 0), BC),
          "setblock %s minecraft:redstone_block" % at(1, -1, 4),
          "setblock %s %sengine_rf[facing=east]" % (at(1, 0, 4), BC),
          "setblock %s %smining_well" % (at(2, 0, 4), BC),
          "setblock %s %sengine_rf" % (at(6, 0, 0), BC),
          "setblock %s %smj_dynamo" % (at(8, 0, 0), BC))
    S.wait(4000)
    S.tp(4, 3, -3, 0, 30)
    S.wait(1000)
    S.shot("notre-blocks", "a creative engine and dynamo (left), an FE engine and Mining Well (further along), two idle "
                           "converters on the right: all drawn as blocks, no error")
    S.cmd("the dynamo holds MJ but nowhere to send FE: still placed", "execute if block %s %smj_dynamo" % (at(1, 0, 0), BC))
    S.cmd("the FE engine is still placed", "execute if block %s %sengine_rf" % (at(1, 0, 4), BC))
    S.echo("the FE engine's buffer (expect 0: no FE source can reach it)", "data get block %s currentFe" % at(1, 0, 4))
    S.cmd("the Mining Well did NOT dig (no FE, no MJ)", "execute unless block %s %stube" % (at(2, -1, 4), BC))
    for label, pos, screen in (("FE engine", (6, 0, 0), "ScreenEngineFE"), ("MJ dynamo", (8, 0, 0), "ScreenDynamoMJ")):
        S.hold("minecraft:air")
        S.tp(pos[0], 0, -3, 0, 15)
        S.aim(*pos)
        S.wait(400)
        S.step(label="open the %s" % label, do="use")
        S.step(do="expectScreen", contains=screen, timeoutSec=10)
        S.wait(500)
        S.shot("notre-gui-" + screen.lower(), "the %s GUI opens and draws its slots, gauge and title" % label)
        S.step(do="close")
    return S


def main():
    energy_rig().write()
    notre_rig().write()


if __name__ == "__main__":
    main()
